//! The site's team explorer (`docs/index.html`) shows the repository's own
//! team files from `docs/teams.js`. GitHub Pages serves `docs/` with no build
//! step, so that file is checked in; this test rebuilds it from the team
//! folders and fails when the two differ, so a change to a team reaches the
//! site in the same pull request.

use std::fs;
use std::path::{Path, PathBuf};

/// The folder the team files are read from, as the site shows their paths.
const SOURCE: &str = "teams";
/// The folders the explorer lists, under `SOURCE`, in the order shown.
const FOLDERS: &[&str] = &["engineering", "dev-team", "shared/includes"];
/// The file the explorer opens on, under `SOURCE`.
const START: &str = "engineering/team.yaml";
/// The generated file, and the command that rewrites it.
const OUTPUT: &str = "docs/teams.js";
const UPDATE: &str = "BRG_UPDATE_SITE=1 tools/cargo-slot cargo test --test site_teams";

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

/// The YAML and Markdown files of one folder: the team file first, then
/// the prompts by name.
fn files(folder: &Path) -> Vec<PathBuf> {
    let mut found: Vec<PathBuf> = fs::read_dir(folder)
        .unwrap_or_else(|e| {
            panic!(
                "read {}: {e}; update SOURCE and FOLDERS in tests/site_teams.rs, then run {UPDATE}",
                folder.display()
            )
        })
        .map(|entry| entry.unwrap().path())
        .filter(|p| p.is_file())
        .filter(|p| matches!(p.extension().and_then(|e| e.to_str()), Some("yaml" | "md")))
        .collect();
    found.sort_by_key(|p| (p.extension().is_some_and(|e| e != "yaml"), p.clone()));
    found
}

/// `docs/teams.js` as it should be: the start file and every listed file's
/// path and text, as one JSON value the page reads.
fn generated() -> String {
    let source = root().join(SOURCE);
    let mut listed = Vec::new();
    for folder in FOLDERS {
        for path in files(&source.join(folder)) {
            let text = fs::read_to_string(&path)
                .unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
            let name = path.file_name().unwrap().to_str().unwrap();
            let shown = format!("{SOURCE}/{folder}/{name}");
            listed.push(serde_json::json!({ "path": shown, "text": text }));
        }
    }
    let start = format!("{SOURCE}/{START}");
    assert!(
        listed.iter().any(|f| f["path"] == start),
        "the start file {start} is not among the listed files; update START in tests/site_teams.rs"
    );
    let data = serde_json::json!({ "start": start, "files": listed });
    format!(
        "// Generated by tests/site_teams.rs from {SOURCE}/; do not edit. To update it, run:\n\
         //   {UPDATE}\n\
         window.TEAM_FILES = {};\n",
        serde_json::to_string_pretty(&data).unwrap()
    )
}

#[test]
fn the_sites_team_files_match_the_team_folders() {
    let want = generated();
    let path = root().join(OUTPUT);
    if std::env::var_os("BRG_UPDATE_SITE").is_some() {
        fs::write(&path, &want).unwrap_or_else(|e| panic!("write {}: {e}", path.display()));
        return;
    }
    let have = fs::read_to_string(&path).unwrap_or_default();
    assert!(
        have == want,
        "{OUTPUT} is out of date with {SOURCE}/ (or missing). Regenerate it with:\n  {UPDATE}"
    );
}
